// Counts n times, so it gives n + 1 steps, and from n = 200 on more than the 200 a run may have.
const countBuild = [
  'import { defineBuild, type Step } from "@artifactory/design-system/stage-build";',
  "",
  "export default defineBuild<{ n: number; w: string }>({",
  "  steps({ n, w }) {",
  '    const word = w === "" ? "ε" : w;',
  "    const steps: Step[] = [];",
  "    for (let turn = 1; turn <= n; turn++) {",
  "      steps.push({",
  "        say: `Volta ${String(turn)}, lendo ${word}.`,",
  '        lines: { 2: "reversed" },',
  "        cells: [",
  '          { row: "contado", column: "Valor", text: String(turn), mark: "strong" },',
  '          { row: "palavra", column: "Valor", text: word },',
  "        ],",
  "      });",
  "    }",
  "    steps.push({",
  "      say: `Devolve ${String(n)}.`,",
  '      lines: { 3: "reversed" },',
  '      rows: { contado: "reversed" },',
  "      cells: [",
  '        { row: "contado", column: "Valor", text: String(n) },',
  '        { row: "palavra", column: "Valor", text: word },',
  "      ],",
  "    });",
  "    return steps;",
  "  },",
  "});",
  "",
].join("\n");

