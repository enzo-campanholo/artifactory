import { readFile } from "node:fs/promises";
import { basename, join } from "node:path";
import typescript from "typescript";

export const referenceFile = "design-system/COMPONENTS.md";
export const regenerateCommand = "pnpm components";
export const designSystemPackage = "@artifactory/design-system/";
const d2TokensFile = "design-system/src/d2-tokens.ts";
const figureColoursFile = "design-system/src/figure-colours.css";

interface ImportableComponent {
  name: string;
  specifier: string;
  file: string;
  build: { specifier: string; file: string } | undefined;
}

export async function importableComponents(root: string): Promise<ImportableComponent[]> {
  const { exports } = JSON.parse(
    await readFile(join(root, "design-system/package.json"), "utf8"),
  ) as { exports: Record<string, string> };
  const stageBuild = exports["./stage-build"];
  // The platform wraps every artifact in its layout, so an artifact never imports a layout. The
  // Stage is documented with the contract its custom builds import.
  return Object.entries(exports)
    .filter(([name, file]) => file.endsWith(".astro") && !name.endsWith("-layout"))
    .map(([name, file]) => ({
      name: basename(file, ".astro"),
      specifier: `${designSystemPackage}${name.replace(/^\.\//, "")}`,
      file: join("design-system", file),
      build:
        name === "./stage" && stageBuild !== undefined
          ? {
              specifier: `${designSystemPackage}stage-build`,
              file: join("design-system", stageBuild),
            }
          : undefined,
    }));
}

export async function componentReference(root: string): Promise<string> {
  const components = await importableComponents(root);
  const sections = await Promise.all(
    components.map(async (component) => {
      const section = componentSection(
        component,
        await readFile(join(root, component.file), "utf8"),
      );
      if (component.build === undefined) return section;
      const { specifier, file } = component.build;
      return [
        section,
        buildSection(specifier, file, await readFile(join(root, file), "utf8")),
      ].join("\n\n");
    }),
  );
  const parts = [
    "# Components",
    `<!-- Generated by \`${regenerateCommand}\` from the design system's source. Don't edit it by hand. -->`,
    ...sections,
    diagramColours(await readFile(join(root, d2TokensFile), "utf8")),
    figureColours(await readFile(join(root, figureColoursFile), "utf8")),
  ];
  return `${parts.join("\n\n")}\n`;
}

function componentSection({ name, specifier, file }: ImportableComponent, source: string): string {
  const frontmatter = /^---\n([\s\S]*?)\n---/.exec(source)?.[1] ?? "";
  const script = typescript.createSourceFile(
    file,
    frontmatter,
    typescript.ScriptTarget.Latest,
    true,
  );
  const props = script.statements.find(
    (statement): statement is typescript.InterfaceDeclaration | typescript.TypeAliasDeclaration =>
      (typescript.isInterfaceDeclaration(statement) ||
        typescript.isTypeAliasDeclaration(statement)) &&
      statement.name.text === "Props",
  );
  if (props === undefined) throw new Error(`${file} has no \`Props\` to document the component`);
  return [
    `## ${name}`,
    `\`import ${name} from "${specifier}";\``,
    docComment(props, script),
    propsSection(props, script),
  ].join("\n\n");
}

function buildSection(specifier: string, file: string, source: string): string {
  const script = typescript.createSourceFile(file, source, typescript.ScriptTarget.Latest, true);
  const exported = script.statements.filter(
    (
      statement,
    ): statement is
      | typescript.InterfaceDeclaration
      | typescript.TypeAliasDeclaration
      | typescript.FunctionDeclaration =>
      (typescript.isInterfaceDeclaration(statement) ||
        typescript.isTypeAliasDeclaration(statement) ||
        typescript.isFunctionDeclaration(statement)) &&
      (typescript.getCombinedModifierFlags(statement) & typescript.ModifierFlags.Export) !== 0,
  );
  return [
    `### The build: \`${specifier}\``,
    "A build file imports only this module. Its default export is `defineBuild({ steps(choice) { … } })` with `choose`, or `defineBuild<{ a: number; b: number }>({ steps(input) { … } })` with `input`.",
    ...exported.map((declaration) => {
      const name = declaration.name?.getText(script) ?? "";
      const shape = typescript.isInterfaceDeclaration(declaration)
        ? propList(membersOf(declaration, script), script)
        : [
            "```ts",
            typescript.isFunctionDeclaration(declaration)
              ? signatureOf(declaration, script)
              : declaration.getText(script).replace(/^export /, ""),
            "```",
          ].join("\n");
      return [`#### \`${name}\``, docComment(declaration, script), shape].join("\n\n");
    }),
  ].join("\n\n");
}

function signatureOf(
  declaration: typescript.FunctionDeclaration,
  script: typescript.SourceFile,
): string {
  const name = declaration.name?.getText(script) ?? "";
  const generics = (declaration.typeParameters ?? []).map((generic) => generic.getText(script));
  const typed = generics.length === 0 ? "" : `<${generics.join(", ")}>`;
  const parameters = declaration.parameters.map((parameter) => parameter.getText(script));
  const returned = declaration.type?.getText(script) ?? "void";
  return `function ${name}${typed}(${parameters.join(", ")}): ${returned};`;
}

type PropsVariant = typescript.PropertySignature[];

function propsSection(
  props: typescript.InterfaceDeclaration | typescript.TypeAliasDeclaration,
  script: typescript.SourceFile,
): string {
  const variants = typescript.isInterfaceDeclaration(props)
    ? [membersOf(props, script)]
    : variantsOf(props.type, script);
  if (variants.length === 1) return ["### Props", propList(variants[0] ?? [], script)].join("\n\n");
  const namesIn = (variant: PropsVariant) => variant.map((member) => propName(member, script));
  return [
    "### Props",
    `Give one of these ${String(variants.length)} sets of props.`,
    ...variants.map((variant, index) => {
      const others = variants.filter((_, otherIndex) => otherIndex !== index).flatMap(namesIn);
      const own = namesIn(variant).filter((name) => !others.includes(name));
      const label = `With ${own.map((name) => `\`${name}\``).join(" and ")}:`;
      return [label, propList(variant, script)].join("\n\n");
    }),
  ].join("\n\n");
}

function variantsOf(type: typescript.TypeNode, script: typescript.SourceFile): PropsVariant[] {
  const members = typescript.isUnionTypeNode(type) ? type.types : [type];
  return members.map((member) => {
    if (!typescript.isTypeReferenceNode(member)) {
      throw new Error(`${script.fileName}: write \`Props\` as interfaces or a union of interfaces`);
    }
    return membersOf(interfaceNamed(member.typeName.getText(script), script), script);
  });
}

function interfaceNamed(
  name: string,
  script: typescript.SourceFile,
): typescript.InterfaceDeclaration {
  const found = script.statements.find(
    (statement): statement is typescript.InterfaceDeclaration =>
      typescript.isInterfaceDeclaration(statement) && statement.name.text === name,
  );
  if (found === undefined) {
    throw new Error(`${script.fileName}: \`${name}\` isn't an interface in the component's script`);
  }
  return found;
}

function membersOf(
  declaration: typescript.InterfaceDeclaration,
  script: typescript.SourceFile,
): PropsVariant {
  const inherited = (declaration.heritageClauses ?? []).flatMap((clause) =>
    clause.types.flatMap((base) =>
      membersOf(interfaceNamed(base.expression.getText(script), script), script),
    ),
  );
  const members = [...declaration.members.filter(typescript.isPropertySignature), ...inherited];
  const required = members.filter((member) => member.questionToken === undefined);
  const optional = members.filter((member) => member.questionToken !== undefined);
  return [...required, ...optional];
}

function propName(member: typescript.PropertySignature, script: typescript.SourceFile): string {
  return member.name.getText(script);
}

function propList(variant: PropsVariant, script: typescript.SourceFile): string {
  if (variant.length === 0) return "None: what goes between its tags is its content.";
  return variant
    .map((member) => {
      // Prettier breaks a long type over lines, which a list item can't hold.
      const type = (member.type?.getText(script) ?? "unknown")
        .replace(/;?\s*\n\s*}/g, " }")
        .replace(/\s*\n\s*/g, " ");
      const presence = member.questionToken === undefined ? "required" : "optional";
      const description = docComment(member, script).replaceAll("\n", "\n  ").replace(/ +$/gm, "");
      return `- \`${propName(member, script)}\` (\`${type}\`, ${presence}): ${description}`;
    })
    .join("\n");
}

// Agents building artifacts read only the reference, so an undocumented component or prop fails.
function docComment(
  node:
    | typescript.InterfaceDeclaration
    | typescript.TypeAliasDeclaration
    | typescript.FunctionDeclaration
    | typescript.PropertySignature,
  script: typescript.SourceFile,
): string {
  const comment = (typescript.getLeadingCommentRanges(script.text, node.pos) ?? [])
    .map((range) => script.text.slice(range.pos, range.end))
    .findLast((text) => text.startsWith("/**"));
  if (comment === undefined) {
    throw new Error(
      `${script.fileName}: \`${node.name?.getText(script) ?? ""}\` has no doc comment`,
    );
  }
  return comment
    .slice(3, -2)
    .split("\n")
    .map((line) => line.replace(/^\s*\* ?/, ""))
    .join("\n")
    .trim();
}

function diagramColours(d2Tokens: string): string {
  const script = typescript.createSourceFile(
    d2TokensFile,
    d2Tokens,
    typescript.ScriptTarget.Latest,
    true,
  );
  const map = script.statements
    .filter(typescript.isVariableStatement)
    .flatMap((statement) => statement.declarationList.declarations)
    .find((declaration) => declaration.name.getText(script) === "tokenOfThemeColour")?.initializer;
  if (map === undefined || !typescript.isObjectLiteralExpression(map)) {
    throw new Error(`${d2TokensFile}: \`tokenOfThemeColour\` isn't an object literal`);
  }
  const coloursOfToken = new Map<string, string[]>();
  for (const property of map.properties.filter(typescript.isPropertyAssignment)) {
    const token = property.initializer.getText(script).slice(1, -1);
    coloursOfToken.set(token, [
      ...(coloursOfToken.get(token) ?? []),
      property.name.getText(script),
    ]);
  }
  return [
    "## Colours in diagrams",
    "D2 draws with its theme's colours, which a D2 file can't choose. The design system replaces each with a token:",
    [...coloursOfToken]
      .map(([token, colours]) => `- \`${token}\`: ${colours.join(", ")}`)
      .join("\n"),
  ].join("\n\n");
}

function figureColours(css: string): string {
  const rules = [
    ...css.matchAll(/\.figure \.((?:fill|stroke)-[a-z]+) \{\s*[a-z]+: var\(([^)]+)\);\s*\}/g),
  ];
  const classes = css.match(/\.figure \.(?:fill|stroke)-/g) ?? [];
  if (rules.length === 0 || rules.length !== classes.length) {
    throw new Error(
      `${figureColoursFile}: write each class as \`.figure .fill-x { fill: var(--token); }\``,
    );
  }
  const colours = (ink: boolean) => {
    const names = [
      ...new Set(
        rules
          .filter(([, , token = ""]) => token.startsWith("--color-text") === ink)
          .map(([, className = ""]) => `\`${className.replace(/^(?:fill|stroke)-/, "")}\``),
      ),
    ];
    return `${names.slice(0, -1).join(", ")} and ${names.at(-1) ?? ""}`;
  };
  return [
    "## Colours in figures",
    "Each class paints an SVG element with a token:",
    rules.map(([, className, token]) => `- \`${className ?? ""}\`: \`${token ?? ""}\``).join("\n"),
    `The ${colours(true)} classes are ink: use them for lines and labels. The ${colours(false)} classes are too faint to read on the page: use them for fills and gridlines, never for text or a line that carries meaning, unless it sits on an ink fill.`,
  ].join("\n\n");
}
